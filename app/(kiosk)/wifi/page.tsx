import { Suspense } from "react";
import { requireGuest } from "@/lib/auth/access";
import { io } from "next/cache";
import QRCode from "qrcode";
import { LockPasswordIcon, SmartPhone01Icon, Wifi01Icon } from "@hugeicons/core-free-icons";
import { HugeiconsIcon, type IconSvgElement } from "@hugeicons/react";

import { ScreenHeader } from "@/components/kiosk/screen-header";
import { getSettings } from "@/lib/db";
import { wifiQrPayload } from "@/lib/wifi";

export default function WifiPage() {
  return (
    <>
      <ScreenHeader title="Wi-Fi" />
      <main className="flex px-4 pt-4 pb-6 md:min-h-0 md:flex-1 md:px-8 md:pt-0">
        <Suspense fallback={<WifiSkeleton />}>
          <WifiContent />
        </Suspense>
      </main>
    </>
  );
}

async function WifiContent() {
  await io();
  await requireGuest();
  const { wifi } = await getSettings();

  // Scanners need maximum contrast, so the code is always black on white
  // regardless of the theme.
  const qrSvg = await QRCode.toString(wifiQrPayload(wifi), {
    type: "svg",
    margin: 0,
    errorCorrectionLevel: "M",
    color: { dark: "#000000", light: "#ffffff" },
  });

  const open = wifi.security === "nopass";

  return (
    <div className="grid flex-1 grid-cols-1 items-stretch gap-4 md:min-h-0 md:grid-cols-[1fr_auto] md:gap-6">
      <div className="flex min-w-0 flex-col justify-center gap-4 md:gap-5">
        <Field icon={Wifi01Icon} label="Network">
          <p data-selectable className="font-heading text-4xl leading-tight font-bold break-words md:text-6xl">
            {wifi.ssid}
          </p>
          {wifi.hidden && (
            <p className="mt-2 text-base text-muted-foreground md:text-xl">
              Hidden network — choose “Other network” on your device and type the name.
            </p>
          )}
        </Field>

        <Field icon={LockPasswordIcon} label="Password">
          {open ? (
            <p className="font-heading text-3xl font-bold md:text-5xl">No password needed</p>
          ) : (
            // Monospace so look-alike characters (0/O, l/1/I) are easy to tell apart.
            <p data-selectable className="font-mono text-3xl leading-tight font-bold break-all md:text-5xl">
              {wifi.password}
            </p>
          )}
        </Field>
      </div>

      <div className="flex flex-col items-center justify-center gap-4 rounded-3xl border bg-card p-5 shadow-sm md:gap-5 md:p-8">
        <div
          className="size-56 rounded-2xl bg-white p-4 md:size-80 md:p-5 [&_svg]:size-full"
          role="img"
          aria-label={`QR code to join ${wifi.ssid}`}
          // SVG markup generated by the qrcode library from our own settings.
          dangerouslySetInnerHTML={{ __html: qrSvg }}
        />
        <p className="flex max-w-80 items-center gap-3 text-base leading-snug md:text-xl">
          <HugeiconsIcon icon={SmartPhone01Icon} className="size-6 shrink-0 text-muted-foreground md:size-8" strokeWidth={2} aria-hidden />
          Point your phone’s camera here to join.
        </p>
      </div>
    </div>
  );
}

function Field({ icon, label, children }: { icon: IconSvgElement; label: string; children: React.ReactNode }) {
  return (
    <section className="rounded-3xl border bg-card p-4 shadow-sm md:p-6">
      <h2 className="mb-2 flex items-center gap-2 text-lg text-muted-foreground md:gap-3 md:text-2xl">
        <HugeiconsIcon icon={icon} className="size-6 md:size-8" strokeWidth={2} aria-hidden />
        {label}
      </h2>
      {children}
    </section>
  );
}

function WifiSkeleton() {
  return (
    <div className="grid flex-1 grid-cols-1 gap-6 md:grid-cols-[1fr_auto]" aria-busy>
      <div className="flex flex-col justify-center gap-5">
        <div className="h-40 animate-pulse rounded-3xl bg-muted" />
        <div className="h-40 animate-pulse rounded-3xl bg-muted" />
      </div>
      <div className="h-64 animate-pulse rounded-3xl bg-muted md:h-full md:w-96" />
    </div>
  );
}
